/* =====================================================================
   Procedure : gold.usp_load_dim_chargeback_reason
   Source    : silver.chargeback_reason_codes
   Target    : gold.dim_chargeback_reason   (type 1 - overwritten on change, no history)
   Load type : Incremental MERGE - new rows inserted, changed rows updated,
               rows gone from the source flagged is_deleted = 1 (never deleted,
               facts may still point at them).

   Purpose
   -------
   One row per card-network chargeback reason code (network + code).
   chargeback_reason_key -1 = Unknown.

   Generated by SQL\gold\tools\New-Type1DimProcedures.ps1 - edit the
   specification there and regenerate rather than editing this file.

   Usage
   -----
     EXEC gold.usp_load_dim_chargeback_reason;
   ===================================================================== */
CREATE OR ALTER PROCEDURE gold.usp_load_dim_chargeback_reason
    @run_id UNIQUEIDENTIFIER = NULL     -- set by gold.usp_load_all; NULL when run on its own
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @ProcName  SYSNAME      = OBJECT_SCHEMA_NAME(@@PROCID) + N'.' + OBJECT_NAME(@@PROCID),
            @Target    SYSNAME      = N'gold.dim_chargeback_reason',
            @StartedAt DATETIME2(3) = SYSUTCDATETIME(),
            @Source    INT,
            @Total     INT,
            @Metrics   NVARCHAR(MAX),
            @Err       NVARCHAR(4000);
    DECLARE @changes TABLE (action NVARCHAR(10), was_deleted BIT, is_deleted BIT);

    BEGIN TRY
        IF OBJECT_ID(@Target, N'U') IS NULL
            THROW 50001, N'gold.dim_chargeback_reason does not exist - run SQL\gold\01_gold_tables.sql first.', 1;

        SELECT @Source = COUNT(*) FROM silver.chargeback_reason_codes;

        BEGIN TRAN;

        -- Unknown member
        IF NOT EXISTS (SELECT 1 FROM gold.dim_chargeback_reason WHERE chargeback_reason_key = -1)
        BEGIN
            SET IDENTITY_INSERT gold.dim_chargeback_reason ON;
            INSERT gold.dim_chargeback_reason (chargeback_reason_key, network, reason_code, description, load_run_id)
            VALUES (-1, 'Unknown', 'Unknown', N'Unknown', @run_id);
            SET IDENTITY_INSERT gold.dim_chargeback_reason OFF;
        END

        MERGE gold.dim_chargeback_reason WITH (HOLDLOCK) AS t
        USING (SELECT network, reason_code, description, category
               FROM silver.chargeback_reason_codes) AS s
           ON t.network = s.network AND t.reason_code = s.reason_code
        WHEN MATCHED AND (t.is_deleted = 1 OR EXISTS (SELECT s.description, s.category
                                                     EXCEPT
                                                     SELECT t.description, t.category))
            THEN UPDATE SET description = s.description, category = s.category,
                            is_deleted = 0, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        WHEN NOT MATCHED BY TARGET
            THEN INSERT (network, reason_code, description, category, load_run_id)
                 VALUES (s.network, s.reason_code, s.description, s.category, @run_id)
        WHEN NOT MATCHED BY SOURCE AND t.chargeback_reason_key <> -1 AND t.is_deleted = 0
            THEN UPDATE SET is_deleted = 1, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        OUTPUT $action, deleted.is_deleted, inserted.is_deleted INTO @changes;

        COMMIT;

        SELECT SourceRows     = @Source,
               Inserted       = (SELECT COUNT(*) FROM @changes WHERE action = 'INSERT'),
               Updated        = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 0),
               FlaggedDeleted = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 1 AND was_deleted = 0),
               TotalRows      = (SELECT COUNT(*) FROM gold.dim_chargeback_reason WHERE chargeback_reason_key <> -1)
        INTO #summary;

        SELECT @Total = TotalRows FROM #summary;
        SET @Metrics = (SELECT * FROM #summary FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Succeeded', @rows_read = @Source, @rows_loaded = @Total, @metrics = @Metrics;

        SELECT * FROM #summary;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK;
        SET @Err = ERROR_MESSAGE();
        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Failed', @error_message = @Err;
        THROW;
    END CATCH
END
GO