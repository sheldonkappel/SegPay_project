/* =====================================================================
   Procedure : gold.usp_load_dim_affiliate
   Source    : silver.affiliates
   Target    : gold.dim_affiliate   (type 1 - overwritten on change, no history)
   Load type : Incremental MERGE - new rows inserted, changed rows updated,
               rows gone from the source flagged is_deleted = 1 (never deleted,
               facts may still point at them).

   Purpose
   -------
   One row per affiliate (traffic partner earning commission).
   affiliate_key -1 = Unknown.

   Notes
   -----
     Facts with no affiliate (direct / organic traffic) map to key -1, labelled Unknown / Direct.

   Generated by SQL\gold\tools\New-Type1DimProcedures.ps1 - edit the
   specification there and regenerate rather than editing this file.

   Usage
   -----
     EXEC gold.usp_load_dim_affiliate;
   ===================================================================== */
CREATE OR ALTER PROCEDURE gold.usp_load_dim_affiliate
    @run_id UNIQUEIDENTIFIER = NULL     -- set by gold.usp_load_all; NULL when run on its own
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @ProcName  SYSNAME      = OBJECT_SCHEMA_NAME(@@PROCID) + N'.' + OBJECT_NAME(@@PROCID),
            @Target    SYSNAME      = N'gold.dim_affiliate',
            @StartedAt DATETIME2(3) = SYSUTCDATETIME(),
            @Source    INT,
            @Total     INT,
            @Metrics   NVARCHAR(MAX),
            @Err       NVARCHAR(4000);
    DECLARE @changes TABLE (action NVARCHAR(10), was_deleted BIT, is_deleted BIT);

    BEGIN TRY
        IF OBJECT_ID(@Target, N'U') IS NULL
            THROW 50001, N'gold.dim_affiliate does not exist - run SQL\gold\01_gold_tables.sql first.', 1;

        SELECT @Source = COUNT(*) FROM silver.affiliates;

        BEGIN TRAN;

        -- Unknown member
        IF NOT EXISTS (SELECT 1 FROM gold.dim_affiliate WHERE affiliate_key = -1)
        BEGIN
            SET IDENTITY_INSERT gold.dim_affiliate ON;
            INSERT gold.dim_affiliate (affiliate_key, affiliate_id, affiliate_name, load_run_id)
            VALUES (-1, 'Unknown', N'Unknown / Direct', @run_id);
            SET IDENTITY_INSERT gold.dim_affiliate OFF;
        END

        MERGE gold.dim_affiliate WITH (HOLDLOCK) AS t
        USING (SELECT affiliate_id, affiliate_name, affiliate_type, commission_pct, status, join_date, country, payout_method
               FROM silver.affiliates) AS s
           ON t.affiliate_id = s.affiliate_id
        WHEN MATCHED AND (t.is_deleted = 1 OR EXISTS (SELECT s.affiliate_name, s.affiliate_type, s.commission_pct, s.status, s.join_date, s.country, s.payout_method
                                                     EXCEPT
                                                     SELECT t.affiliate_name, t.affiliate_type, t.commission_pct, t.status, t.join_date, t.country, t.payout_method))
            THEN UPDATE SET affiliate_name = s.affiliate_name, affiliate_type = s.affiliate_type, commission_pct = s.commission_pct, status = s.status, join_date = s.join_date, country = s.country, payout_method = s.payout_method,
                            is_deleted = 0, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        WHEN NOT MATCHED BY TARGET
            THEN INSERT (affiliate_id, affiliate_name, affiliate_type, commission_pct, status, join_date, country, payout_method, load_run_id)
                 VALUES (s.affiliate_id, s.affiliate_name, s.affiliate_type, s.commission_pct, s.status, s.join_date, s.country, s.payout_method, @run_id)
        WHEN NOT MATCHED BY SOURCE AND t.affiliate_key <> -1 AND t.is_deleted = 0
            THEN UPDATE SET is_deleted = 1, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        OUTPUT $action, deleted.is_deleted, inserted.is_deleted INTO @changes;

        COMMIT;

        SELECT SourceRows     = @Source,
               Inserted       = (SELECT COUNT(*) FROM @changes WHERE action = 'INSERT'),
               Updated        = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 0),
               FlaggedDeleted = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 1 AND was_deleted = 0),
               TotalRows      = (SELECT COUNT(*) FROM gold.dim_affiliate WHERE affiliate_key <> -1)
        INTO #summary;

        SELECT @Total = TotalRows FROM #summary;
        SET @Metrics = (SELECT * FROM #summary FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Succeeded', @rows_read = @Source, @rows_loaded = @Total, @metrics = @Metrics;

        SELECT * FROM #summary;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK;
        SET @Err = ERROR_MESSAGE();
        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Failed', @error_message = @Err;
        THROW;
    END CATCH
END
GO