/* =====================================================================
   Procedure : gold.usp_load_dim_response_code
   Source    : silver.response_codes
   Target    : gold.dim_response_code   (type 1 - overwritten on change, no history)
   Load type : Incremental MERGE - new rows inserted, changed rows updated,
               rows gone from the source flagged is_deleted = 1 (never deleted,
               facts may still point at them).

   Purpose
   -------
   One row per authorization response code, classed Approved / Soft decline / Hard decline (ref.response_code_class).
   response_code_key -1 = Unknown.

   Notes
   -----
     Edit ref.response_code_class to change which declines count as soft (retry) or hard.

   Generated by SQL\gold\tools\New-Type1DimProcedures.ps1 - edit the
   specification there and regenerate rather than editing this file.

   Usage
   -----
     EXEC gold.usp_load_dim_response_code;
   ===================================================================== */
CREATE OR ALTER PROCEDURE gold.usp_load_dim_response_code
    @run_id UNIQUEIDENTIFIER = NULL     -- set by gold.usp_load_all; NULL when run on its own
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @ProcName  SYSNAME      = OBJECT_SCHEMA_NAME(@@PROCID) + N'.' + OBJECT_NAME(@@PROCID),
            @Target    SYSNAME      = N'gold.dim_response_code',
            @StartedAt DATETIME2(3) = SYSUTCDATETIME(),
            @Source    INT,
            @Total     INT,
            @Metrics   NVARCHAR(MAX),
            @Err       NVARCHAR(4000);
    DECLARE @changes TABLE (action NVARCHAR(10), was_deleted BIT, is_deleted BIT);

    BEGIN TRY
        IF OBJECT_ID(@Target, N'U') IS NULL
            THROW 50001, N'gold.dim_response_code does not exist - run SQL\gold\01_gold_tables.sql first.', 1;

        SELECT @Source = COUNT(*) FROM silver.response_codes;

        BEGIN TRAN;

        -- Unknown member
        IF NOT EXISTS (SELECT 1 FROM gold.dim_response_code WHERE response_code_key = -1)
        BEGIN
            SET IDENTITY_INSERT gold.dim_response_code ON;
            INSERT gold.dim_response_code (response_code_key, response_code, description, load_run_id)
            VALUES (-1, 'Unknown', 'Unknown', @run_id);
            SET IDENTITY_INSERT gold.dim_response_code OFF;
        END

        MERGE gold.dim_response_code WITH (HOLDLOCK) AS t
        USING (SELECT r.response_code, r.description, c.response_group, c.decline_type, CAST(CASE WHEN c.response_group = 'Approved' THEN 1 ELSE 0 END AS BIT) AS is_approved
               FROM silver.response_codes r LEFT JOIN ref.response_code_class c ON c.response_code = r.response_code) AS s
           ON t.response_code = s.response_code
        WHEN MATCHED AND (t.is_deleted = 1 OR EXISTS (SELECT s.description, s.response_group, s.decline_type, s.is_approved
                                                     EXCEPT
                                                     SELECT t.description, t.response_group, t.decline_type, t.is_approved))
            THEN UPDATE SET description = s.description, response_group = s.response_group, decline_type = s.decline_type, is_approved = s.is_approved,
                            is_deleted = 0, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        WHEN NOT MATCHED BY TARGET
            THEN INSERT (response_code, description, response_group, decline_type, is_approved, load_run_id)
                 VALUES (s.response_code, s.description, s.response_group, s.decline_type, s.is_approved, @run_id)
        WHEN NOT MATCHED BY SOURCE AND t.response_code_key <> -1 AND t.is_deleted = 0
            THEN UPDATE SET is_deleted = 1, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        OUTPUT $action, deleted.is_deleted, inserted.is_deleted INTO @changes;

        COMMIT;

        SELECT SourceRows     = @Source,
               Inserted       = (SELECT COUNT(*) FROM @changes WHERE action = 'INSERT'),
               Updated        = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 0),
               FlaggedDeleted = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 1 AND was_deleted = 0),
               TotalRows      = (SELECT COUNT(*) FROM gold.dim_response_code WHERE response_code_key <> -1)
        INTO #summary;

        SELECT @Total = TotalRows FROM #summary;
        SET @Metrics = (SELECT * FROM #summary FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Succeeded', @rows_read = @Source, @rows_loaded = @Total, @metrics = @Metrics;

        SELECT * FROM #summary;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK;
        SET @Err = ERROR_MESSAGE();
        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Failed', @error_message = @Err;
        THROW;
    END CATCH
END
GO