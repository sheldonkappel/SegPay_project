/* =====================================================================
   Procedure : gold.usp_load_dim_site
   Source    : silver.sites
   Target    : gold.dim_site   (type 1 - overwritten on change, no history)
   Load type : Incremental MERGE - new rows inserted, changed rows updated,
               rows gone from the source flagged is_deleted = 1 (never deleted,
               facts may still point at them).

   Purpose
   -------
   One row per site (website a merchant sells through).
   site_key -1 = Unknown.

   Notes
   -----
     merchant_id is the owner per the sites file. 12 sites list merchants MRC-00201 - MRC-00205
     while their transactions name another merchant (see silver.usp_load_sites); facts take the
     merchant from the transaction, not from here.

   Generated by SQL\gold\tools\New-Type1DimProcedures.ps1 - edit the
   specification there and regenerate rather than editing this file.

   Usage
   -----
     EXEC gold.usp_load_dim_site;
   ===================================================================== */
CREATE OR ALTER PROCEDURE gold.usp_load_dim_site
    @run_id UNIQUEIDENTIFIER = NULL     -- set by gold.usp_load_all; NULL when run on its own
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @ProcName  SYSNAME      = OBJECT_SCHEMA_NAME(@@PROCID) + N'.' + OBJECT_NAME(@@PROCID),
            @Target    SYSNAME      = N'gold.dim_site',
            @StartedAt DATETIME2(3) = SYSUTCDATETIME(),
            @Source    INT,
            @Total     INT,
            @Metrics   NVARCHAR(MAX),
            @Err       NVARCHAR(4000);
    DECLARE @changes TABLE (action NVARCHAR(10), was_deleted BIT, is_deleted BIT);

    BEGIN TRY
        IF OBJECT_ID(@Target, N'U') IS NULL
            THROW 50001, N'gold.dim_site does not exist - run SQL\gold\01_gold_tables.sql first.', 1;

        SELECT @Source = COUNT(*) FROM silver.sites;

        BEGIN TRAN;

        -- Unknown member
        IF NOT EXISTS (SELECT 1 FROM gold.dim_site WHERE site_key = -1)
        BEGIN
            SET IDENTITY_INSERT gold.dim_site ON;
            INSERT gold.dim_site (site_key, site_id, site_name, load_run_id)
            VALUES (-1, -1, N'Unknown', @run_id);
            SET IDENTITY_INSERT gold.dim_site OFF;
        END

        MERGE gold.dim_site WITH (HOLDLOCK) AS t
        USING (SELECT site_id, site_name, site_url, category, status, launch_date, billing_descriptor, merchant_id
               FROM silver.sites) AS s
           ON t.site_id = s.site_id
        WHEN MATCHED AND (t.is_deleted = 1 OR EXISTS (SELECT s.site_name, s.site_url, s.category, s.status, s.launch_date, s.billing_descriptor, s.merchant_id
                                                     EXCEPT
                                                     SELECT t.site_name, t.site_url, t.category, t.status, t.launch_date, t.billing_descriptor, t.merchant_id))
            THEN UPDATE SET site_name = s.site_name, site_url = s.site_url, category = s.category, status = s.status, launch_date = s.launch_date, billing_descriptor = s.billing_descriptor, merchant_id = s.merchant_id,
                            is_deleted = 0, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        WHEN NOT MATCHED BY TARGET
            THEN INSERT (site_id, site_name, site_url, category, status, launch_date, billing_descriptor, merchant_id, load_run_id)
                 VALUES (s.site_id, s.site_name, s.site_url, s.category, s.status, s.launch_date, s.billing_descriptor, s.merchant_id, @run_id)
        WHEN NOT MATCHED BY SOURCE AND t.site_key <> -1 AND t.is_deleted = 0
            THEN UPDATE SET is_deleted = 1, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        OUTPUT $action, deleted.is_deleted, inserted.is_deleted INTO @changes;

        COMMIT;

        SELECT SourceRows     = @Source,
               Inserted       = (SELECT COUNT(*) FROM @changes WHERE action = 'INSERT'),
               Updated        = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 0),
               FlaggedDeleted = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 1 AND was_deleted = 0),
               TotalRows      = (SELECT COUNT(*) FROM gold.dim_site WHERE site_key <> -1)
        INTO #summary;

        SELECT @Total = TotalRows FROM #summary;
        SET @Metrics = (SELECT * FROM #summary FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Succeeded', @rows_read = @Source, @rows_loaded = @Total, @metrics = @Metrics;

        SELECT * FROM #summary;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK;
        SET @Err = ERROR_MESSAGE();
        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Failed', @error_message = @Err;
        THROW;
    END CATCH
END
GO