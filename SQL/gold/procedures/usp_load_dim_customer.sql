/* =====================================================================
   Procedure : gold.usp_load_dim_customer
   Source    : silver.customers
   Target    : gold.dim_customer   (type 1 - overwritten on change, no history)
   Load type : Incremental MERGE - new rows inserted, changed rows updated,
               rows gone from the source flagged is_deleted = 1 (never deleted,
               facts may still point at them).

   Purpose
   -------
   One row per customer (cardholder account).
   customer_key -1 = Unknown.

   Notes
   -----
     Personal data (email, postal code) is deliberately left in silver.

   Generated by SQL\gold\tools\New-Type1DimProcedures.ps1 - edit the
   specification there and regenerate rather than editing this file.

   Usage
   -----
     EXEC gold.usp_load_dim_customer;
   ===================================================================== */
CREATE OR ALTER PROCEDURE gold.usp_load_dim_customer
    @run_id UNIQUEIDENTIFIER = NULL     -- set by gold.usp_load_all; NULL when run on its own
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @ProcName  SYSNAME      = OBJECT_SCHEMA_NAME(@@PROCID) + N'.' + OBJECT_NAME(@@PROCID),
            @Target    SYSNAME      = N'gold.dim_customer',
            @StartedAt DATETIME2(3) = SYSUTCDATETIME(),
            @Source    INT,
            @Total     INT,
            @Metrics   NVARCHAR(MAX),
            @Err       NVARCHAR(4000);
    DECLARE @changes TABLE (action NVARCHAR(10), was_deleted BIT, is_deleted BIT);

    BEGIN TRY
        IF OBJECT_ID(@Target, N'U') IS NULL
            THROW 50001, N'gold.dim_customer does not exist - run SQL\gold\01_gold_tables.sql first.', 1;

        SELECT @Source = COUNT(*) FROM silver.customers;

        BEGIN TRAN;

        -- Unknown member
        IF NOT EXISTS (SELECT 1 FROM gold.dim_customer WHERE customer_key = -1)
        BEGIN
            SET IDENTITY_INSERT gold.dim_customer ON;
            INSERT gold.dim_customer (customer_key, customer_id, load_run_id)
            VALUES (-1, 'Unknown', @run_id);
            SET IDENTITY_INSERT gold.dim_customer OFF;
        END

        MERGE gold.dim_customer WITH (HOLDLOCK) AS t
        USING (SELECT customer_id, country, created_at AS created_date, marketing_opt_in
               FROM silver.customers) AS s
           ON t.customer_id = s.customer_id
        WHEN MATCHED AND (t.is_deleted = 1 OR EXISTS (SELECT s.country, s.created_date, s.marketing_opt_in
                                                     EXCEPT
                                                     SELECT t.country, t.created_date, t.marketing_opt_in))
            THEN UPDATE SET country = s.country, created_date = s.created_date, marketing_opt_in = s.marketing_opt_in,
                            is_deleted = 0, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        WHEN NOT MATCHED BY TARGET
            THEN INSERT (customer_id, country, created_date, marketing_opt_in, load_run_id)
                 VALUES (s.customer_id, s.country, s.created_date, s.marketing_opt_in, @run_id)
        WHEN NOT MATCHED BY SOURCE AND t.customer_key <> -1 AND t.is_deleted = 0
            THEN UPDATE SET is_deleted = 1, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        OUTPUT $action, deleted.is_deleted, inserted.is_deleted INTO @changes;

        COMMIT;

        SELECT SourceRows     = @Source,
               Inserted       = (SELECT COUNT(*) FROM @changes WHERE action = 'INSERT'),
               Updated        = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 0),
               FlaggedDeleted = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 1 AND was_deleted = 0),
               TotalRows      = (SELECT COUNT(*) FROM gold.dim_customer WHERE customer_key <> -1)
        INTO #summary;

        SELECT @Total = TotalRows FROM #summary;
        SET @Metrics = (SELECT * FROM #summary FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Succeeded', @rows_read = @Source, @rows_loaded = @Total, @metrics = @Metrics;

        SELECT * FROM #summary;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK;
        SET @Err = ERROR_MESSAGE();
        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Failed', @error_message = @Err;
        THROW;
    END CATCH
END
GO