/* =====================================================================
   Procedure : gold.usp_load_dim_package
   Source    : silver.packages
   Target    : gold.dim_package   (type 1 - overwritten on change, no history)
   Load type : Incremental MERGE - new rows inserted, changed rows updated,
               rows gone from the source flagged is_deleted = 1 (never deleted,
               facts may still point at them).

   Purpose
   -------
   One row per package (price point: one-time, recurring or trial).
   package_key -1 = Unknown.

   Notes
   -----
     About 350 transactions reference a package not in silver.packages; they map to Unknown.

   Generated by SQL\gold\tools\New-Type1DimProcedures.ps1 - edit the
   specification there and regenerate rather than editing this file.

   Usage
   -----
     EXEC gold.usp_load_dim_package;
   ===================================================================== */
CREATE OR ALTER PROCEDURE gold.usp_load_dim_package
    @run_id UNIQUEIDENTIFIER = NULL     -- set by gold.usp_load_all; NULL when run on its own
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @ProcName  SYSNAME      = OBJECT_SCHEMA_NAME(@@PROCID) + N'.' + OBJECT_NAME(@@PROCID),
            @Target    SYSNAME      = N'gold.dim_package',
            @StartedAt DATETIME2(3) = SYSUTCDATETIME(),
            @Source    INT,
            @Total     INT,
            @Metrics   NVARCHAR(MAX),
            @Err       NVARCHAR(4000);
    DECLARE @changes TABLE (action NVARCHAR(10), was_deleted BIT, is_deleted BIT);

    BEGIN TRY
        IF OBJECT_ID(@Target, N'U') IS NULL
            THROW 50001, N'gold.dim_package does not exist - run SQL\gold\01_gold_tables.sql first.', 1;

        SELECT @Source = COUNT(*) FROM silver.packages;

        BEGIN TRAN;

        -- Unknown member
        IF NOT EXISTS (SELECT 1 FROM gold.dim_package WHERE package_key = -1)
        BEGIN
            SET IDENTITY_INSERT gold.dim_package ON;
            INSERT gold.dim_package (package_key, package_id, package_name, load_run_id)
            VALUES (-1, -1, N'Unknown', @run_id);
            SET IDENTITY_INSERT gold.dim_package OFF;
        END

        MERGE gold.dim_package WITH (HOLDLOCK) AS t
        USING (SELECT package_id, package_name, site_id, billing_model, initial_price, rebill_price, currency, trial_days, rebill_period_days, status
               FROM silver.packages) AS s
           ON t.package_id = s.package_id
        WHEN MATCHED AND (t.is_deleted = 1 OR EXISTS (SELECT s.package_name, s.site_id, s.billing_model, s.initial_price, s.rebill_price, s.currency, s.trial_days, s.rebill_period_days, s.status
                                                     EXCEPT
                                                     SELECT t.package_name, t.site_id, t.billing_model, t.initial_price, t.rebill_price, t.currency, t.trial_days, t.rebill_period_days, t.status))
            THEN UPDATE SET package_name = s.package_name, site_id = s.site_id, billing_model = s.billing_model, initial_price = s.initial_price, rebill_price = s.rebill_price, currency = s.currency, trial_days = s.trial_days, rebill_period_days = s.rebill_period_days, status = s.status,
                            is_deleted = 0, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        WHEN NOT MATCHED BY TARGET
            THEN INSERT (package_id, package_name, site_id, billing_model, initial_price, rebill_price, currency, trial_days, rebill_period_days, status, load_run_id)
                 VALUES (s.package_id, s.package_name, s.site_id, s.billing_model, s.initial_price, s.rebill_price, s.currency, s.trial_days, s.rebill_period_days, s.status, @run_id)
        WHEN NOT MATCHED BY SOURCE AND t.package_key <> -1 AND t.is_deleted = 0
            THEN UPDATE SET is_deleted = 1, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        OUTPUT $action, deleted.is_deleted, inserted.is_deleted INTO @changes;

        COMMIT;

        SELECT SourceRows     = @Source,
               Inserted       = (SELECT COUNT(*) FROM @changes WHERE action = 'INSERT'),
               Updated        = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 0),
               FlaggedDeleted = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 1 AND was_deleted = 0),
               TotalRows      = (SELECT COUNT(*) FROM gold.dim_package WHERE package_key <> -1)
        INTO #summary;

        SELECT @Total = TotalRows FROM #summary;
        SET @Metrics = (SELECT * FROM #summary FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Succeeded', @rows_read = @Source, @rows_loaded = @Total, @metrics = @Metrics;

        SELECT * FROM #summary;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK;
        SET @Err = ERROR_MESSAGE();
        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Failed', @error_message = @Err;
        THROW;
    END CATCH
END
GO