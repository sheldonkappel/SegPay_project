/* =====================================================================
   Procedure : gold.usp_load_dim_card_bin
   Source    : silver.bin_reference
   Target    : gold.dim_card_bin   (type 1 - overwritten on change, no history)
   Load type : Incremental MERGE - new rows inserted, changed rows updated,
               rows gone from the source flagged is_deleted = 1 (never deleted,
               facts may still point at them).

   Purpose
   -------
   One row per card BIN (first 6 digits): brand, card type, tier, issuing bank and country.
   card_bin_key -1 = Unknown.

   Notes
   -----
     silver.bin_reference covers 243 BINs; ~14,800 transactions use other BINs and map to Unknown.

   Generated by SQL\gold\tools\New-Type1DimProcedures.ps1 - edit the
   specification there and regenerate rather than editing this file.

   Usage
   -----
     EXEC gold.usp_load_dim_card_bin;
   ===================================================================== */
CREATE OR ALTER PROCEDURE gold.usp_load_dim_card_bin
    @run_id UNIQUEIDENTIFIER = NULL     -- set by gold.usp_load_all; NULL when run on its own
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @ProcName  SYSNAME      = OBJECT_SCHEMA_NAME(@@PROCID) + N'.' + OBJECT_NAME(@@PROCID),
            @Target    SYSNAME      = N'gold.dim_card_bin',
            @StartedAt DATETIME2(3) = SYSUTCDATETIME(),
            @Source    INT,
            @Total     INT,
            @Metrics   NVARCHAR(MAX),
            @Err       NVARCHAR(4000);
    DECLARE @changes TABLE (action NVARCHAR(10), was_deleted BIT, is_deleted BIT);

    BEGIN TRY
        IF OBJECT_ID(@Target, N'U') IS NULL
            THROW 50001, N'gold.dim_card_bin does not exist - run SQL\gold\01_gold_tables.sql first.', 1;

        SELECT @Source = COUNT(*) FROM silver.bin_reference;

        BEGIN TRAN;

        -- Unknown member
        IF NOT EXISTS (SELECT 1 FROM gold.dim_card_bin WHERE card_bin_key = -1)
        BEGIN
            SET IDENTITY_INSERT gold.dim_card_bin ON;
            INSERT gold.dim_card_bin (card_bin_key, bin, issuer_name, load_run_id)
            VALUES (-1, 'Unknown', N'Unknown', @run_id);
            SET IDENTITY_INSERT gold.dim_card_bin OFF;
        END

        MERGE gold.dim_card_bin WITH (HOLDLOCK) AS t
        USING (SELECT bin, card_brand, card_type, card_category, issuer_name, issuer_country
               FROM silver.bin_reference) AS s
           ON t.bin = s.bin
        WHEN MATCHED AND (t.is_deleted = 1 OR EXISTS (SELECT s.card_brand, s.card_type, s.card_category, s.issuer_name, s.issuer_country
                                                     EXCEPT
                                                     SELECT t.card_brand, t.card_type, t.card_category, t.issuer_name, t.issuer_country))
            THEN UPDATE SET card_brand = s.card_brand, card_type = s.card_type, card_category = s.card_category, issuer_name = s.issuer_name, issuer_country = s.issuer_country,
                            is_deleted = 0, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        WHEN NOT MATCHED BY TARGET
            THEN INSERT (bin, card_brand, card_type, card_category, issuer_name, issuer_country, load_run_id)
                 VALUES (s.bin, s.card_brand, s.card_type, s.card_category, s.issuer_name, s.issuer_country, @run_id)
        WHEN NOT MATCHED BY SOURCE AND t.card_bin_key <> -1 AND t.is_deleted = 0
            THEN UPDATE SET is_deleted = 1, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        OUTPUT $action, deleted.is_deleted, inserted.is_deleted INTO @changes;

        COMMIT;

        SELECT SourceRows     = @Source,
               Inserted       = (SELECT COUNT(*) FROM @changes WHERE action = 'INSERT'),
               Updated        = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 0),
               FlaggedDeleted = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 1 AND was_deleted = 0),
               TotalRows      = (SELECT COUNT(*) FROM gold.dim_card_bin WHERE card_bin_key <> -1)
        INTO #summary;

        SELECT @Total = TotalRows FROM #summary;
        SET @Metrics = (SELECT * FROM #summary FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Succeeded', @rows_read = @Source, @rows_loaded = @Total, @metrics = @Metrics;

        SELECT * FROM #summary;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK;
        SET @Err = ERROR_MESSAGE();
        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Failed', @error_message = @Err;
        THROW;
    END CATCH
END
GO