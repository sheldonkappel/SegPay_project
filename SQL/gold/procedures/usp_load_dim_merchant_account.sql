/* =====================================================================
   Procedure : gold.usp_load_dim_merchant_account
   Source    : silver.merchant_accounts
   Target    : gold.dim_merchant_account   (type 1 - overwritten on change, no history)
   Load type : Incremental MERGE - new rows inserted, changed rows updated,
               rows gone from the source flagged is_deleted = 1 (never deleted,
               facts may still point at them).

   Purpose
   -------
   One row per merchant processing account (MID) at an acquiring bank.
   merchant_account_key -1 = Unknown.

   Generated by SQL\gold\tools\New-Type1DimProcedures.ps1 - edit the
   specification there and regenerate rather than editing this file.

   Usage
   -----
     EXEC gold.usp_load_dim_merchant_account;
   ===================================================================== */
CREATE OR ALTER PROCEDURE gold.usp_load_dim_merchant_account
    @run_id UNIQUEIDENTIFIER = NULL     -- set by gold.usp_load_all; NULL when run on its own
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @ProcName  SYSNAME      = OBJECT_SCHEMA_NAME(@@PROCID) + N'.' + OBJECT_NAME(@@PROCID),
            @Target    SYSNAME      = N'gold.dim_merchant_account',
            @StartedAt DATETIME2(3) = SYSUTCDATETIME(),
            @Source    INT,
            @Total     INT,
            @Metrics   NVARCHAR(MAX),
            @Err       NVARCHAR(4000);
    DECLARE @changes TABLE (action NVARCHAR(10), was_deleted BIT, is_deleted BIT);

    BEGIN TRY
        IF OBJECT_ID(@Target, N'U') IS NULL
            THROW 50001, N'gold.dim_merchant_account does not exist - run SQL\gold\01_gold_tables.sql first.', 1;

        SELECT @Source = COUNT(*) FROM silver.merchant_accounts;

        BEGIN TRAN;

        -- Unknown member
        IF NOT EXISTS (SELECT 1 FROM gold.dim_merchant_account WHERE merchant_account_key = -1)
        BEGIN
            SET IDENTITY_INSERT gold.dim_merchant_account ON;
            INSERT gold.dim_merchant_account (merchant_account_key, mid, acquirer_name, load_run_id)
            VALUES (-1, 'Unknown', 'Unknown', @run_id);
            SET IDENTITY_INSERT gold.dim_merchant_account OFF;
        END

        MERGE gold.dim_merchant_account WITH (HOLDLOCK) AS t
        USING (SELECT mid, merchant_id, acquirer_name, currency_group, mcc, effective_from, status
               FROM silver.merchant_accounts) AS s
           ON t.mid = s.mid
        WHEN MATCHED AND (t.is_deleted = 1 OR EXISTS (SELECT s.merchant_id, s.acquirer_name, s.currency_group, s.mcc, s.effective_from, s.status
                                                     EXCEPT
                                                     SELECT t.merchant_id, t.acquirer_name, t.currency_group, t.mcc, t.effective_from, t.status))
            THEN UPDATE SET merchant_id = s.merchant_id, acquirer_name = s.acquirer_name, currency_group = s.currency_group, mcc = s.mcc, effective_from = s.effective_from, status = s.status,
                            is_deleted = 0, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        WHEN NOT MATCHED BY TARGET
            THEN INSERT (mid, merchant_id, acquirer_name, currency_group, mcc, effective_from, status, load_run_id)
                 VALUES (s.mid, s.merchant_id, s.acquirer_name, s.currency_group, s.mcc, s.effective_from, s.status, @run_id)
        WHEN NOT MATCHED BY SOURCE AND t.merchant_account_key <> -1 AND t.is_deleted = 0
            THEN UPDATE SET is_deleted = 1, updated_at = SYSUTCDATETIME(), load_run_id = @run_id
        OUTPUT $action, deleted.is_deleted, inserted.is_deleted INTO @changes;

        COMMIT;

        SELECT SourceRows     = @Source,
               Inserted       = (SELECT COUNT(*) FROM @changes WHERE action = 'INSERT'),
               Updated        = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 0),
               FlaggedDeleted = (SELECT COUNT(*) FROM @changes WHERE action = 'UPDATE' AND is_deleted = 1 AND was_deleted = 0),
               TotalRows      = (SELECT COUNT(*) FROM gold.dim_merchant_account WHERE merchant_account_key <> -1)
        INTO #summary;

        SELECT @Total = TotalRows FROM #summary;
        SET @Metrics = (SELECT * FROM #summary FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Succeeded', @rows_read = @Source, @rows_loaded = @Total, @metrics = @Metrics;

        SELECT * FROM #summary;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK;
        SET @Err = ERROR_MESSAGE();
        EXEC audit.usp_log_load @run_id = @run_id, @proc_name = @ProcName, @target_table = @Target,
             @started_at = @StartedAt, @status = 'Failed', @error_message = @Err;
        THROW;
    END CATCH
END
GO